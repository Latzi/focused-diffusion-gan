#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Create the 'advbox' variant of the FDGAN training code: the adversarial gradient of the generator is confined to the
box (background pixels of the clean-image prediction are detached before the generator's discriminator pass). The
discriminator update, R1, the diffusion loss and all reconstruction and colour terms are untouched.

Run from the repository root:   python3 make_advbox_files.py
Reads (never modified):  guided_diffusion/train_util_coco_fdgan_late_band.py
                         scripts/image_train_Run2_3_10_FDGAN_COCO_LateBand.py
Writes (refuses to overwrite): guided_diffusion/train_util_coco_fdgan_late_band_advbox.py
                               scripts/image_train_Run2_3_10_FDGAN_COCO_LateBand_advbox.py
Every anchor must occur exactly once in the source file, otherwise nothing is written. A unified diff is printed.
"""
import argparse, difflib, io, os, sys

ap = argparse.ArgumentParser()
ap.add_argument("--train-util", default="guided_diffusion/train_util_coco_fdgan_late_band.py")
ap.add_argument("--train-script", default="scripts/image_train_Run2_3_10_FDGAN_COCO_LateBand.py")
ap.add_argument("--out-util", default="guided_diffusion/train_util_coco_fdgan_late_band_advbox.py")
ap.add_argument("--out-script", default="scripts/image_train_Run2_3_10_FDGAN_COCO_LateBand_advbox.py")
a = ap.parse_args()

def rd(p):
    with io.open(p, encoding="utf-8") as f: return f.read()

def replace_once(text, old, new, what):
    n = text.count(old)
    if n != 1:
        sys.exit(f"ABORT: anchor for '{what}' found {n} times (expected 1): {old!r}")
    return text.replace(old, new)

for p in (a.out_util, a.out_script):
    if os.path.exists(p): sys.exit(f"ABORT: {p} already exists; delete it yourself if you want it regenerated")

# ------------------------------------------------------------------ training loop
tu = rd(a.train_util)
tu2 = replace_once(tu, "        enable_small_roi_d: bool = False,\n",
                   "        enable_small_roi_d: bool = False,\n        adv_grad_in_box_only: bool = False,\n", "constructor flag")
tu2 = replace_once(tu2, "        self.enable_small_roi_d = bool(enable_small_roi_d)\n",
                   "        self.enable_small_roi_d = bool(enable_small_roi_d)\n"
                   "        self.adv_grad_in_box_only = bool(adv_grad_in_box_only)   # advbox variant\n", "attribute")
OLD_G = "fake_pred_g = mainD_fwd(x0_pred.float(), bb_mask_sel.detach().float())"
NEW_G = ("x0_for_adv = x0_pred\n"
         "{i}if self.adv_grad_in_box_only:\n"
         "{i}    # advbox: the generator's adversarial gradient reaches only the box pixels; D still sees the whole image\n"
         "{i}    m_adv = bb_mask_sel.detach().to(x0_pred.dtype)\n"
         "{i}    x0_for_adv = x0_pred * m_adv + x0_pred.detach() * (1.0 - m_adv)\n"
         "{i}fake_pred_g = mainD_fwd(x0_for_adv.float(), bb_mask_sel.detach().float())")
lines = tu2.split("\n")
hits = [k for k, l in enumerate(lines) if l.strip() == OLD_G]
if len(hits) != 1: sys.exit(f"ABORT: generator adversarial pass found {len(hits)} times (expected 1)")
indent = lines[hits[0]][: len(lines[hits[0]]) - len(lines[hits[0]].lstrip())]
lines[hits[0]] = indent + NEW_G.format(i=indent)
tu2 = "\n".join(lines)
tu2 = replace_once(tu2, '            logger.logkv("gan_warmup_steps", float(getattr(self, "gan_warmup_steps", 0)))\n',
                   '            logger.logkv("gan_warmup_steps", float(getattr(self, "gan_warmup_steps", 0)))\n'
                   '            logger.logkv("adv_grad_in_box_only", float(getattr(self, "adv_grad_in_box_only", False)))\n', "log flag")
tu2 = tu2.replace('"""', '"""ADVBOX VARIANT (generated by make_advbox_files.py): adv_grad_in_box_only flag added; otherwise identical.\n', 1) if tu2.lstrip().startswith('"""') else "# ADVBOX VARIANT (generated by make_advbox_files.py): adv_grad_in_box_only flag added; otherwise identical.\n" + tu2

# ------------------------------------------------------------------ training script
ts = rd(a.train_script)
ts2 = replace_once(ts, "from guided_diffusion.train_util_coco_fdgan_late_band import TrainLoop",
                   "from guided_diffusion.train_util_coco_fdgan_late_band_advbox import TrainLoop", "loop import")
ts2 = replace_once(ts2, "        enable_small_roi_d=False,\n", "        enable_small_roi_d=False,\n        adv_grad_in_box_only=False,\n", "argparse default")
ts2 = replace_once(ts2, "        enable_small_roi_d=args.enable_small_roi_d,\n",
                   "        enable_small_roi_d=args.enable_small_roi_d,\n        adv_grad_in_box_only=args.adv_grad_in_box_only,\n", "TrainLoop argument")

# ------------------------------------------------------------------ write + show the diffs
for src, dst, old, new in ((a.train_util, a.out_util, tu, tu2), (a.train_script, a.out_script, ts, ts2)):
    with io.open(dst, "w", encoding="utf-8", newline="\n") as f: f.write(new)
    print(f"\n===== {dst}  (from {src})")
    for l in difflib.unified_diff(old.split("\n"), new.split("\n"), fromfile=src, tofile=dst, lineterm="", n=1):
        print(l)
print("\nadvbox files written. The job file passes --adv_grad_in_box_only True.")
